.section .text

.extern irq_dispatch

# One entry stub per PIC line. Each saves the general registers, calls
# irq_dispatch(n) with a 16-byte aligned stack and returns with iretq.
.macro IRQ_STUB n
.globl irq_stub_\n
irq_stub_\n:
    push %r15
    push %r14
    push %r13
    push %r12
    push %r11
    push %r10
    push %r9
    push %r8
    push %rbp
    push %rdi
    push %rsi
    push %rdx
    push %rcx
    push %rbx
    push %rax

    mov %rsp, %rbx
    and $~15, %rsp
    cld
    mov $\n, %edi
    call irq_dispatch
    mov %rbx, %rsp

    pop %rax
    pop %rbx
    pop %rcx
    pop %rdx
    pop %rsi
    pop %rdi
    pop %rbp
    pop %r8
    pop %r9
    pop %r10
    pop %r11
    pop %r12
    pop %r13
    pop %r14
    pop %r15
    iretq
.endm

